import os
import json
import uuid
import jwt
import logging
from datetime import datetime, timedelta, timezone
from django.conf import settings
from django.db import connection, transaction, DatabaseError
from rest_framework.exceptions import AuthenticationFailed, ValidationError, PermissionDenied
from accounts.models import Employee, Customer, Warehouse, Role, EmployeeRole


logger = logging.getLogger(__name__)

# bcrypt cost factor used for every hash written by this service. Matches the
# cost already used by pgcrypto crypt()/gen_salt() in the existing schema.
BCRYPT_SALT_COST = 10

# bcrypt() consumes at most 72 bytes of the password, so longer inputs cannot
# be verified reliably and are rejected before they reach the database.
MAX_PASSWORD_LENGTH = 72

# public.customers.password is text and holds two schemes today: bcrypt hashes
# written by this service and legacy plain text from the imported retail
# dataset. The scheme is detected from the stored value, never from the input.
BCRYPT_PREFIX_SQL = "left(password, 4) IN ('$2a$', '$2b$', '$2y$')"
NOT_BCRYPT_SQL = (
    "password IS NOT NULL AND left(password, 4) NOT IN ('$2a$', '$2b$', '$2y$')"
)


class SupabaseAuthService:
    @staticmethod
    def get_jwt_secret():
        return os.getenv('SUPABASE_JWT_SECRET') or settings.SECRET_KEY

    @staticmethod
    def generate_token_pair(auth_user_id, email, role, warehouse_id=None):
        jwt_secret = SupabaseAuthService.get_jwt_secret()
        now = datetime.now(timezone.utc)
        
        access_payload = {
            'sub': str(auth_user_id),
            'email': email,
            'role': role,
            'warehouse_id': warehouse_id,
            'iat': int(now.timestamp()),
            'exp': int((now + timedelta(days=7)).timestamp()),
            'aud': 'authenticated',
        }
        
        refresh_payload = {
            'sub': str(auth_user_id),
            'iat': int(now.timestamp()),
            'exp': int((now + timedelta(days=30)).timestamp()),
            'token_type': 'refresh',
        }
        
        access_token = jwt.encode(access_payload, jwt_secret, algorithm='HS256')
        refresh_token = jwt.encode(refresh_payload, jwt_secret, algorithm='HS256')
        
        return {
            'access_token': access_token,
            'refresh_token': refresh_token,
            'expires_in': 7 * 24 * 3600,
            'token_type': 'Bearer'
        }

    @staticmethod
    def verify_token(token_string):
        """
        Verifies a JWT token. First attempts verification with SUPABASE_JWT_SECRET,
        then falls back to settings.SECRET_KEY or unverified payload inspection if needed.
        """
        secrets = [SupabaseAuthService.get_jwt_secret(), settings.SECRET_KEY]
        last_exception = None
        
        for secret in set(secrets):
            try:
                payload = jwt.decode(
                    token_string,
                    secret,
                    algorithms=['HS256'],
                    options={'verify_aud': False}
                )
                return payload
            except jwt.ExpiredSignatureError:
                raise AuthenticationFailed("Token has expired. Please log in again.")
            except jwt.InvalidTokenError as e:
                last_exception = e
                continue
        
        # If token was issued directly by Supabase Auth with an external RS256/HS256 key
        try:
            unverified = jwt.decode(token_string, options={"verify_signature": False})
            if 'sub' in unverified:
                return unverified
        except Exception:
            pass

        raise AuthenticationFailed(f"Invalid authentication token: {last_exception}")

    @classmethod
    def _generate_customer_id(cls):
        """Allocate a unique customer_id matching the existing 'U#######' format.

        public.customers.customer_id is a plain text PK with no sequence or
        default, so ids are not auto-generated by the database.
        """
        import random
        for width in (7, 8, 9):
            for _ in range(50):
                candidate = f"U{random.randint(10 ** (width - 1), 10 ** width - 1)}"
                with connection.cursor() as cursor:
                    cursor.execute("SELECT 1 FROM public.customers WHERE customer_id = %s;", [candidate])
                    if not cursor.fetchone():
                        return candidate
        raise ValidationError({"detail": "Could not allocate a customer ID. Please try again."})

    @classmethod
    def register_customer(cls, email, password, full_name, gender=None, **extra_fields):
        # Normalise email so capitalisation / stray whitespace never breaks lookup.
        email = cls._normalize_email(email)
        customer_name = str(full_name or '').strip()
        if not customer_name:
            raise ValidationError({"full_name": "Customer name is required."})

        # Reject duplicate emails on the real customer table (public.customers).
        with connection.cursor() as cursor:
            cursor.execute("SELECT 1 FROM public.customers WHERE LOWER(email) = LOWER(%s) LIMIT 1;", [email])
            if cursor.fetchone():
                raise ValidationError({"email": "An account with this email address already exists."})

        customer_id = cls._generate_customer_id()

        # Password is stored as a bcrypt hash produced inside PostgreSQL
        # (pgcrypto crypt/gen_salt) in the customers.password column - never
        # as plain text. Plain-text never leaves this statement.
        try:
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    INSERT INTO public.customers (customer_id, customer_name, gender, email, password)
                    VALUES (%s, %s, %s, %s, crypt(%s, gen_salt('bf', 10)));
                    """,
                    [customer_id, customer_name, (gender or None), email, password],
                )
        except Exception:
            raise ValidationError({"detail": "Could not create the customer account. Please try again."})

        # The customer_id is the trusted subject for JWTs and profile lookups.
        tokens = cls.generate_token_pair(customer_id, email, Role.CUSTOMER)
        return {
            'user': {
                'id': customer_id,
                'customer_id': customer_id,
                'email': email,
                'full_name': customer_name,
                'gender': gender,
                'role': Role.CUSTOMER,
            },
            'tokens': tokens
        }

    # Trusted mapping from app_users.role (lowercase) to the Role constants the
    # API and frontend routes rely on. Never taken from client input.
    STAFF_ROLE_MAP = {
        'admin': Role.ADMIN,
        'warehouse_manager': Role.WAREHOUSE_MANAGER,
        'delivery': Role.DELIVERY_PARTNER,
    }

    @staticmethod
    def _normalize_email(email):
        return str(email or '').strip().lower()

    @staticmethod
    def _check_password_shape(password):
        """Reject unusable input before it reaches crypt().

        The message is deliberately the same generic one used for bad
        credentials, so an over-long or empty password never hints at whether
        the email exists.
        """
        if not isinstance(password, str) or not password:
            raise AuthenticationFailed("Invalid email or password.")
        if len(password.encode('utf-8')) > MAX_PASSWORD_LENGTH:
            raise AuthenticationFailed("Invalid email or password.")

    @staticmethod
    def _database_failed(context, exc):
        """Map a database failure to a safe, generic client error.

        Only the exception class is logged: psycopg2 messages quote the
        offending statement, which in these queries contains the submitted
        password.
        """
        logger.error("%s: database error (%s)", context, type(exc).__name__)
        raise AuthenticationFailed("Unable to sign in right now. Please try again later.")

    @classmethod
    def verify_staff_credentials(cls, email, password):
        """Authenticate a staff member against public.app_users.

        Password verification is performed server-side with pgcrypto bcrypt:
        `password_hash = crypt(%s, password_hash)` is evaluated inside the
        database, so the stored hash is never returned to the application or
        the browser.
        """
        cls._check_password_shape(password)
        norm = cls._normalize_email(email)
        try:
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    SELECT user_id, email, role, is_active,
                           (password_hash = crypt(%s, password_hash)) AS password_ok
                    FROM public.app_users
                    WHERE LOWER(email) = LOWER(%s)
                    LIMIT 1;
                    """,
                    [password, norm],
                )
                row = cursor.fetchone()
        except DatabaseError as exc:
            cls._database_failed("staff login", exc)

        if not row:
            raise AuthenticationFailed("Invalid email or password.")

        user_id, db_email, db_role, is_active, password_ok = row
        if not is_active:
            raise AuthenticationFailed("This account is inactive. Please contact the administrator.")
        if not password_ok:
            raise AuthenticationFailed("Invalid email or password.")

        role = cls.STAFF_ROLE_MAP.get(str(db_role).strip().lower())
        if not role:
            raise AuthenticationFailed("Unrecognized staff role.")

        return {
            'user_id': str(user_id),
            'email': db_email,
            'role': role,
            'is_active': True,
        }

    @classmethod
    def verify_customer_credentials(cls, email, password):
        """Authenticate a customer against public.customers.

        public.customers.password holds two kinds of values: bcrypt hashes
        written by this service (pgcrypto crypt/gen_salt) and legacy plain
        text carried over from the imported retail dataset. The scheme is
        detected from the stored value and both branches are evaluated inside
        PostgreSQL, so a stored password - hash or plain - is never fetched
        into the application or returned to the browser.

        `crypt()` is only ever called on a bcrypt value; feeding it a plain-
        text value would make pgcrypto silently fall back to DES, which
        truncates the secret and could never match the stored string.

        A legacy plain-text row that authenticates successfully is re-hashed
        with bcrypt immediately (see _upgrade_customer_password), so plain
        text stops being the authentication secret after first sign-in.
        """
        cls._check_password_shape(password)
        norm = cls._normalize_email(email)
        try:
            with connection.cursor() as cursor:
                cursor.execute(
                    f"""
                    SELECT customer_id, customer_name, gender, email,
                           CASE
                             WHEN password IS NULL THEN FALSE
                             WHEN {BCRYPT_PREFIX_SQL}
                               THEN (password = crypt(%s, password))
                             ELSE (password = %s)
                           END AS password_ok,
                           COALESCE({BCRYPT_PREFIX_SQL}, TRUE) AS is_bcrypt
                    FROM public.customers
                    WHERE LOWER(email) = LOWER(%s)
                    LIMIT 1;
                    """,
                    [password, password, norm],
                )
                row = cursor.fetchone()
        except DatabaseError as exc:
            cls._database_failed("customer login", exc)

        if not row or not row[4]:
            # Same generic message for unknown email and wrong password so the
            # endpoint does not leak which emails are registered.
            raise AuthenticationFailed("Invalid email or password.")

        customer_id, customer_name, gender, cust_email, _, is_bcrypt = row

        if not is_bcrypt:
            cls._upgrade_customer_password(customer_id, password)

        return {
            'customer_id': str(customer_id),
            'customer_name': customer_name,
            'gender': gender,
            'email': cust_email,
        }

    @classmethod
    def _upgrade_customer_password(cls, customer_id, password):
        """Replace a verified legacy plain-text password with a bcrypt hash.

        The hash is built by pgcrypto from the password that was just
        verified, so the plain text is never read out of the database. The
        extra `AND password = %s` predicate makes the write compare-and-set:
        if the row changed concurrently, nothing is overwritten.

        A failure here is not fatal - the credentials already matched - and
        the row simply stays eligible for the batched
        `migrate_customer_passwords` command.
        """
        try:
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    UPDATE public.customers
                    SET password = crypt(%s, gen_salt('bf', %s))
                    WHERE customer_id = %s
                      AND password IS NOT NULL
                      AND left(password, 4) NOT IN ('$2a$', '$2b$', '$2y$')
                      AND password = %s;
                    """,
                    [password, BCRYPT_SALT_COST, customer_id, password],
                )
        except DatabaseError as exc:
            # Log the exception class only; never the message or the SQL.
            logger.error(
                "customer password upgrade failed for a customer_id (database error: %s)",
                type(exc).__name__,
            )

    @classmethod
    def login(cls, email_or_username, password):
        norm = cls._normalize_email(email_or_username)

        # ---- Staff path: public.app_users (bcrypt verified server-side) ----
        try:
            with connection.cursor() as cursor:
                cursor.execute("SELECT 1 FROM public.app_users WHERE LOWER(email) = LOWER(%s) LIMIT 1;", [norm])
                is_staff = cursor.fetchone() is not None
        except DatabaseError as exc:
            cls._database_failed("login", exc)

        if is_staff:
            staff = cls.verify_staff_credentials(norm, password)
            tokens = cls.generate_token_pair(staff['user_id'], staff['email'], staff['role'])
            display_name = staff['email'].split('@')[0].replace('.', ' ').replace('_', ' ').title()
            return {
                'user': {
                    'id': staff['user_id'],
                    'email': staff['email'],
                    'full_name': display_name,
                    'role': staff['role'],
                    'warehouse_id': None,
                    'is_active': True,
                },
                'tokens': tokens
            }

        # ---- Customer path: public.customers (never creates an account) ----
        customer = cls.verify_customer_credentials(norm, password)
        tokens = cls.generate_token_pair(customer['customer_id'], customer['email'], Role.CUSTOMER)
        return {
            'user': {
                'id': customer['customer_id'],
                'customer_id': customer['customer_id'],
                'email': customer['email'],
                'full_name': customer['customer_name'],
                'gender': customer['gender'],
                'role': Role.CUSTOMER,
            },
            'tokens': tokens
        }

    @classmethod
    def admin_create_employee(cls, admin_user, email, password, full_name, role, warehouse_id=None, phone=None):
        # 1. Role validation
        if role not in [EmployeeRole.WAREHOUSE_MANAGER, EmployeeRole.DELIVERY_PARTNER]:
            raise ValidationError({"role": f"Admin can only create WAREHOUSE_MANAGER or DELIVERY_PARTNER. Provided: {role}"})

        # 2. Warehouse association validation
        if role == EmployeeRole.WAREHOUSE_MANAGER:
            if not warehouse_id:
                raise ValidationError({"warehouse_id": "Warehouse ID is required when creating a Warehouse Manager."})
            if not Warehouse.objects.filter(warehouse_id=warehouse_id).exists():
                raise ValidationError({"warehouse_id": f"Warehouse with ID '{warehouse_id}' does not exist."})
        else:
            warehouse_id = None

        email = email.lower().strip()

        # 3. Check if email already in use
        with connection.cursor() as cursor:
            cursor.execute("SELECT id FROM auth.users WHERE LOWER(email) = LOWER(%s);", [email])
            if cursor.fetchone():
                raise ValidationError({"email": "An account with this email address already exists."})

        if Employee.objects.filter(email__iexact=email).exists():
            raise ValidationError({"email": "An employee with this email already exists."})

        auth_user_id = str(uuid.uuid4())
        now = datetime.now(timezone.utc)

        with transaction.atomic():
            # Create user in auth.users
            with connection.cursor() as cursor:
                cursor.execute("""
                    INSERT INTO auth.users (
                        id, email, encrypted_password, email_confirmed_at,
                        created_at, updated_at, role, aud,
                        raw_app_meta_data, raw_user_meta_data, is_sso_user, is_anonymous
                    ) VALUES (
                        %s, %s, crypt(%s, gen_salt('bf', 10)), %s,
                        %s, %s, 'authenticated', 'authenticated',
                        '{"provider":"email","providers":["email"]}'::jsonb,
                        %s::jsonb, FALSE, FALSE
                    );
                """, [
                    auth_user_id,
                    email,
                    password,
                    now,
                    now,
                    now,
                    f'{{"full_name":"{full_name}","role":"{role}"}}'
                ])

            # Insert employee record
            with connection.cursor() as cursor:
                cursor.execute("""
                    INSERT INTO public.employees (
                        auth_user_id, full_name, email, phone, role, warehouse_id, is_active, created_at, updated_at
                    ) VALUES (
                        %s, %s, %s, %s, %s, %s, TRUE, %s, %s
                    ) RETURNING employee_id;
                """, [
                    auth_user_id,
                    full_name,
                    email,
                    phone,
                    role,
                    warehouse_id,
                    now,
                    now
                ])
                employee_id = cursor.fetchone()[0]

        return {
            'employee_id': employee_id,
            'auth_user_id': auth_user_id,
            'full_name': full_name,
            'email': email,
            'phone': phone,
            'role': role,
            'warehouse_id': warehouse_id,
            'is_active': True,
        }

    @classmethod
    def seed_initial_admin(cls, email, password, full_name="System Administrator", phone=None):
        email = email.lower().strip()
        existing = Employee.objects.filter(email__iexact=email, role=EmployeeRole.ADMIN).first()
        if existing:
            return existing, False

        auth_user_id = str(uuid.uuid4())
        now = datetime.now(timezone.utc)

        with transaction.atomic():
            # Check if user exists in auth.users
            with connection.cursor() as cursor:
                cursor.execute("SELECT id FROM auth.users WHERE LOWER(email) = LOWER(%s);", [email])
                row = cursor.fetchone()
                if row:
                    auth_user_id = row[0]
                    cursor.execute("""
                        UPDATE auth.users 
                        SET encrypted_password = crypt(%s, gen_salt('bf', 10)),
                            updated_at = %s
                        WHERE id = %s;
                    """, [password, now, auth_user_id])
                else:
                    cursor.execute("""
                        INSERT INTO auth.users (
                            id, email, encrypted_password, email_confirmed_at,
                            created_at, updated_at, role, aud,
                            raw_app_meta_data, raw_user_meta_data, is_sso_user, is_anonymous
                        ) VALUES (
                            %s, %s, crypt(%s, gen_salt('bf', 10)), %s,
                            %s, %s, 'authenticated', 'authenticated',
                            '{"provider":"email","providers":["email"]}'::jsonb,
                            %s::jsonb, FALSE, FALSE
                        );
                    """, [
                        auth_user_id,
                        email,
                        password,
                        now,
                        now,
                        now,
                        f'{{"full_name":"{full_name}","role":"ADMIN"}}'
                    ])

            with connection.cursor() as cursor:
                cursor.execute("""
                    INSERT INTO public.employees (
                        auth_user_id, full_name, email, phone, role, warehouse_id, is_active, created_at, updated_at
                    ) VALUES (
                        %s, %s, %s, %s, 'ADMIN', NULL, TRUE, %s, %s
                    )
                    ON CONFLICT (email) DO UPDATE 
                    SET role = 'ADMIN', is_active = TRUE
                    RETURNING employee_id;
                """, [
                    auth_user_id,
                    full_name,
                    email,
                    phone,
                    now,
                    now
                ])
                employee_id = cursor.fetchone()[0]

        admin_emp = Employee.objects.get(employee_id=employee_id)
        return admin_emp, True

