"""Create the indexes and the uniqueness the wishlist / cart / orders reads need.

Why this exists
    `public.cart`, `public.wishlist` and `public.orders` arrived from the data
    import with nothing but their primary keys indexed. Every customer-scoped
    request therefore scanned the whole table (165k, 306k and 1,000,000 rows),
    which measured 0.2-0.3s per query on Neon before these indexes.

    The (customer_id, product_id) unique indexes additionally enforce the
    documented business rule - one wishlist row and one cart line per customer
    and product - at the database level, which is what makes "add again" a safe
    quantity increment instead of a duplicate row.

Nothing here changes stored data: duplicate groups were verified to be zero
before the unique indexes were introduced, and the command is idempotent
(CREATE ... IF NOT EXISTS), so it can be re-run at any time.

Usage
    python manage.py ensure_ecommerce_indexes
    python manage.py ensure_ecommerce_indexes --dry-run
"""

from django.core.management.base import BaseCommand
from django.db import connection, DatabaseError


# (name, statement) - parameterless DDL, generated by this command only.
INDEXES = [
    ('wishlist_customer_idx',
     'CREATE INDEX IF NOT EXISTS wishlist_customer_idx '
     'ON public.wishlist (customer_id)'),
    ('wishlist_customer_product_unique',
     'CREATE UNIQUE INDEX IF NOT EXISTS wishlist_customer_product_unique '
     'ON public.wishlist (customer_id, product_id)'),
    ('cart_customer_idx',
     'CREATE INDEX IF NOT EXISTS cart_customer_idx '
     'ON public.cart (customer_id)'),
    ('cart_customer_product_unique',
     'CREATE UNIQUE INDEX IF NOT EXISTS cart_customer_product_unique '
     'ON public.cart (customer_id, product_id)'),
    ('orders_customer_idx',
     'CREATE INDEX IF NOT EXISTS orders_customer_idx '
     'ON public.orders (customer_id)'),
    ('customers_email_lower_idx',
     'CREATE INDEX IF NOT EXISTS customers_email_lower_idx '
     'ON public.customers (LOWER(email))'),
]


class Command(BaseCommand):
    help = (
        "Create the customer-scoped indexes and the (customer_id, product_id) "
        "unique indexes used by the wishlist, cart and order APIs."
    )

    def add_arguments(self, parser):
        parser.add_argument(
            '--dry-run', action='store_true',
            help="Report what would be created without touching the schema.",
        )

    def handle(self, *args, **options):
        with connection.cursor() as cursor:
            for name, statement in INDEXES:
                if options['dry_run']:
                    cursor.execute(
                        "SELECT 1 FROM pg_class WHERE relname = %s;", [name]
                    )
                    state = 'already present' if cursor.fetchone() else 'would create'
                    self.stdout.write(f"{state}: {name}")
                    continue

                # Django runs in autocommit, so each statement commits on its
                # own and a failure leaves the earlier ones in place.
                try:
                    cursor.execute(statement)
                except DatabaseError as exc:
                    # Only the class is reported; a unique-index failure would
                    # otherwise echo duplicate rows from the data.
                    self.stderr.write(
                        f"could not create {name} (database error: {type(exc).__name__})"
                    )
                    continue
                self.stdout.write(self.style.SUCCESS(f"ready: {name}"))

        if not options['dry_run']:
            # Fresh planner statistics so the new indexes are actually chosen.
            with connection.cursor() as cursor:
                for table in ('wishlist', 'cart', 'orders', 'customers'):
                    try:
                        cursor.execute(f"ANALYZE public.{table};")
                    except DatabaseError as exc:
                        self.stderr.write(
                            f"analyze skipped for {table} ({type(exc).__name__})"
                        )
            self.stdout.write(self.style.SUCCESS("Indexes are in place."))
